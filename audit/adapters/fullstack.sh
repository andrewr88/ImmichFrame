#!/bin/sh
# Fullstack language adapter for the audit system (C#/.NET + TypeScript/Svelte).
#
# The audit core (audit/audit.sh, audit/scan.sh, audit/arch.sh) is
# language-agnostic. Every project-specific decision — which files to track, how
# to prioritise them, the build/test commands embedded in generated prompts, and
# the catalog of static analyzers — lives here. The core sources exactly one
# adapter, selected by AUDIT_ADAPTER, via `. audit/adapters/${AUDIT_ADAPTER}.sh`.
#
# ImmichFrame is two stacks in one repo (an ASP.NET Core 8 API plus a SvelteKit
# SPA), so this is deliberately ONE composite adapter rather than one per
# language: the core can only source a single file, and a `dotnet.sh` /
# `svelte.sh` split would force two disjoint databases over one codebase. Hence
# the name. Both halves are covered here: every seam below handles C# and
# TypeScript/Svelte paths, and the scan catalog drives both toolchains.
#
# See audit/ADAPTERS.md for the contract and audit/adapters/go.sh for the
# reference implementation this follows.
#
# The architecture members (audit_arch_*) are implemented at the bottom of this
# file, so `arch-sweep` works under this adapter. Phase 3 shells out to neither
# dotnet nor npm: the whole report is git + grep + awk + sqlite3 over the tree.
#
# POSIX sh only. The core is `#!/bin/sh` and SOURCES this file, so a bashism
# here breaks the core itself: no arrays, no `[[`, no `local`, no `${var,,}`.
#
# ---------------------------------------------------------------------------
# Adapter contract (functions/variables the core calls)
# ---------------------------------------------------------------------------
#
# Discovery & priority (used by audit/audit.sh cmd_sync):
#   audit_discover_sources      Repo-relative source paths, one per line.
#   audit_priority_score <path> Integer 0-100; higher = swept sooner.
#   audit_trivial_comment_regex ERE for comment-only lines (optional hook).
#
# Verify commands (used by audit/audit.sh prompt templates):
#   audit_verify_build_cmd   Print the build command string (no trailing NL).
#   audit_verify_test_cmd    Print the test command string (no trailing NL).
#
# Scan tool catalog (used by audit/scan.sh). The core owns the generic harness
# (file-id cache, sql_escape/rel_path/truncate_str/count_lines, apply_batch,
# batch header/footer, file sync, "all analyzers missing" check, summary
# rendering). The adapter owns the tools:
#   AUDIT_SCAN_TOOLS        Space-separated, ordered list of tool ids.
#   scan_<id>               One driver per id; sets the counter/state vars.
#   audit_scan_label <id>   Display name for the summary table.
#   audit_scan_state <id>   "ran" or "missing".
#   audit_scan_new/_dup/_skip <id>   Per-tool counters.
#
# The drivers rely on these being defined by the core before they run: DB,
# REPO_ROOT, TMP_DIR, FILES_CACHE, and the helper functions lookup_fid,
# sql_escape, rel_path, truncate_str, count_lines, apply_batch,
# write_batch_header, write_batch_footer.
#
# Architecture report (used by audit/arch.sh arch-sweep). Section C is the
# core's; A, B, D and E are this adapter's:
#   audit_arch_preflight            Preconditions + AUDIT_ARCH_MODULE + graph inputs.
#   audit_arch_resolve_nondir <arg> C# namespace or $lib alias -> directory.
#   audit_arch_has_sources <dir>    Zero if <dir> holds tracked sources.
#   audit_arch_build_graph          Both import graphs + the scoped file lists.
#   audit_arch_section_a/_b/_d/_e   Section bodies, headers included.
#
# The arch members run with DB, REPO_ROOT, TMP_DIR, TARGET_SCOPE, TARGET_DIR and
# TARGET_FILE_LIKE in scope.

# ---------------------------------------------------------------------------
# Discovery & priority
# ---------------------------------------------------------------------------

# The four C# project directories of ImmichFrame.sln. Named explicitly rather
# than discovered from the .sln so that discovery never sweeps in stray *.cs
# under docs/, misc/ or a scratch directory.
AUDIT_CS_PROJECTS="ImmichFrame.Core ImmichFrame.WebApi ImmichFrame.Core.Tests ImmichFrame.WebApi.Tests"

# The SvelteKit project root, the one source under it that is never audited, and
# the one hand-written source that lives OUTSIDE src/.
#
# immichFrameApi.ts is generated by oazapfts from openApi/swagger.json and is
# marked DO NOT MODIFY; tracking it would queue an agent to hand-edit generated
# code, exactly as the obj/ and bin/ exclusions above avoid for C#.
#
# static/ is otherwise images and a webmanifest, but pwa-service-worker.js is
# 100 lines of hand-written security-relevant logic: it caches a bearer auth
# secret received over postMessage and injects 'Authorization: Bearer <secret>'
# onto intercepted video-stream requests. It is named explicitly rather than
# swept up by a static/*.js glob, for the same reason AUDIT_CS_PROJECTS is a
# list and not a find: a future minified vendor drop in static/ must not silently
# enter the audit queue.
AUDIT_WEB_ROOT="immichFrame.Web"
AUDIT_WEB_GENERATED="immichFrame.Web/src/lib/immichFrameApi.ts"
AUDIT_WEB_SERVICE_WORKER="immichFrame.Web/static/pwa-service-worker.js"

# audit_discover_sources: repo-relative list of files to track.
#
# Sourced from git's index (`git ls-files`), like go.sh, NOT from a bare find.
# Rooting a find at the project directories does not keep untracked files out —
# a C# scratch or work-in-progress file has to live inside a project to compile,
# so it lands squarely in the search path. Tracking those is actively harmful:
# they consume sweep-queue slots, and `git log -1` reports no history for them,
# so they enter the files table with last_commit='unknown' and their staleness
# path never fires (the core treats an empty/unknown hash as non-trivial and can
# never re-stamp coverage against it).
#
# The obj/ and bin/ exclusions stay path-based rather than leaning on
# .gitignore, so the intent survives a gitignore edit. Both hold generated
# compiler output (AssemblyInfo, GlobalUsings, the NSwag-generated ImmichApi) —
# machine-written, regenerated on every build, and meaningless to audit.
#
# Directory.Packages.props is tracked as a source file even though it is not
# C#: `dotnet list package --vulnerable` reports per *package*, but a finding
# row needs a file_id from a tracked path. This repo uses Central Package
# Management, so that one file holds every version and is where a bump is
# actually made — it is the correct owner for dependency CVEs. See
# scan_vulnerable below.
#
# The `[ -f ]` filter drops index entries whose working-tree copy is absent
# (an `rm` without `git rm`), which would otherwise abort cmd_sync's `wc -l`
# under set -e. git ls-files emits bare repo-relative paths, which is already
# the contract (the core strips a leading "./" defensively anyway).
#
# The frontend half is rooted at immichFrame.Web/src, with two named additions.
# src/ is the bulk of the hand-written code; what sits above it is mostly build
# configuration (vite/svelte/tailwind/postcss config, tsconfig) that no file
# sweep should queue. The exceptions are named explicitly:
#
#   package.json  tracked as a source file even though it is not TypeScript —
#                 `npm audit` reports per *package* and a finding row needs a
#                 file_id, so package.json owns the dependency advisories the
#                 way Directory.Packages.props owns the NuGet ones. See
#                 scan_npmaudit.
#   static/pwa-service-worker.js  NOT build configuration: hand-written code
#                 that handles a bearer credential (see the constant above).
#                 ESLint already lints it, so leaving it untracked did not make
#                 it unanalysed — it made every finding against it get thrown
#                 away as an untracked-path skip.
audit_discover_sources() {
    for d in $AUDIT_CS_PROJECTS; do
        git ls-files -- "$d/*.cs"
    done \
    | grep -Ev '(^|/)(obj|bin)/' \
    | while IFS= read -r p; do [ -f "$p" ] && printf '%s\n' "$p"; done
    git ls-files -- 'Directory.Packages.props' \
    | while IFS= read -r p; do [ -f "$p" ] && printf '%s\n' "$p"; done
    git ls-files -- "$AUDIT_WEB_ROOT/src/*.ts" "$AUDIT_WEB_ROOT/src/*.svelte" \
                    "$AUDIT_WEB_ROOT/src/*.js" \
    | grep -Fxv "$AUDIT_WEB_GENERATED" \
    | while IFS= read -r p; do [ -f "$p" ] && printf '%s\n' "$p"; done
    git ls-files -- "$AUDIT_WEB_ROOT/package.json" \
    | while IFS= read -r p; do [ -f "$p" ] && printf '%s\n' "$p"; done
    git ls-files -- "$AUDIT_WEB_SERVICE_WORKER" \
    | while IFS= read -r p; do [ -f "$p" ] && printf '%s\n' "$p"; done
}

# audit_priority_score <path>: priority score for a repo-relative path.
#
# Path-prefix scoring only — no git-churn weighting, because the core already
# surfaces staleness separately (v_next_audit_target orders on coverage age).
# The *.Tests/* arm comes FIRST so that a test file never inherits the score of
# the production area it mirrors.
audit_priority_score() {
    priority=50
    case "$1" in
        # Audited, but last: no production blast radius.
        *.Tests/*)                              priority=25 ;;
        # Settings loading — holds the auth secret, Immich API keys, webhooks.
        ImmichFrame.WebApi/Helpers/Config/*)    priority=95 ;;
        # The composition root: DI, middleware order, auth wiring.
        ImmichFrame.WebApi/Program.cs)          priority=90 ;;
        # Auth middleware, SanitizeString, the profile registry.
        ImmichFrame.WebApi/Helpers/*)           priority=85 ;;
        # Request handling — client-supplied input lands here.
        ImmichFrame.WebApi/Controllers/*)       priority=80 ;;
        # Asset pools: the busiest and most intricate area of the codebase.
        ImmichFrame.Core/Logic/*)               priority=70 ;;
        # Outbound HTTP and credential handling.
        ImmichFrame.Core/Api/*)                 priority=65 ;;
        ImmichFrame.Core/Services/*)            priority=65 ;;
        # DTO boundary — the client-leak surface.
        ImmichFrame.WebApi/Models/*)            priority=55 ;;
        ImmichFrame.Core/Models/*)              priority=55 ;;

        # --- frontend ---------------------------------------------------
        # Nothing here outranks the C# config surface at 95, which is where
        # the auth secret is issued and stored. The SPA only ever holds a
        # copy of one, and only in the service worker.
        #
        # Ordering inside this block is load-bearing. A `case` pattern's `*`
        # matches '/' too, so `immichFrame.Web/src/lib/*.ts` also matches
        # stores/, hooks/, components/ and constants/. Those four arms must
        # therefore come FIRST; the .ts arm then only ever sees files sitting
        # directly in src/lib.

        # The PWA service worker: the only frontend file that holds a
        # credential. It caches the bearer auth secret and signs outbound
        # video-stream requests with it, so it outranks everything else on
        # this side of the stack — but stays below the C# config surface at
        # 95, which is where the secret is actually issued.
        immichFrame.Web/static/pwa-service-worker.js) priority=75 ;;
        # Entry points and data loading (+page.ts / +layout.ts run first).
        immichFrame.Web/src/routes/*)           priority=65 ;;
        # Shared mutable state and the lifecycle hooks that drive it.
        immichFrame.Web/src/lib/stores/*)       priority=60 ;;
        immichFrame.Web/src/lib/hooks/*)        priority=60 ;;
        # Presentation: bugs here are visible, not structural.
        immichFrame.Web/src/lib/components/*)   priority=50 ;;
        # Literal tables — lowest-value audit target in the repo.
        immichFrame.Web/src/lib/constants/*)    priority=35 ;;
        # Cross-cutting helpers directly under src/lib (utils, constants, index).
        immichFrame.Web/src/lib/*.ts)           priority=60 ;;
        # Dependency advisories land here; see scan_npmaudit.
        immichFrame.Web/package.json)           priority=50 ;;

        # Everything else in Core, Directory.Packages.props, and
        # immichFrame.Web/src/app.d.ts keep 50.
    esac
    printf '%s' "$priority"
}

# audit_trivial_comment_regex: ERE for comment-only lines, repo-wide.
#
# The core takes ONE regex for the whole repo, so this covers both languages'
# line-comment forms:
#
#   //  — C#, TypeScript and JavaScript
#   <!-- ... -->  — Svelte markup (single-line only)
#
# Two properties have to hold on both arms.
#
# (1) A comment whose marker is GLUED to the text is meaningful, never trivial.
#     '///' is a C# XML doc comment (this codebase uses '/// <summary>' to
#     record design rationale in ProfileRegistry.cs and ProfileServices.cs) and
#     in TypeScript a triple-slash directive ('/// <reference types="..." />')
#     that changes what the compiler sees. '//nolint' and '//go:build' are the
#     same shape. Requiring whitespace-or-EOL after '//' excludes them all, and
#     '/**' JSDoc never matches because it has one slash before the star.
#
# (2) A comment whose FIRST TOKEN is a directive is equally meaningful — and in
#     TS/JS/Svelte, unlike C# and Go, those carry a SPACE after the opener:
#
#       // @ts-expect-error          // @ts-ignore
#       // eslint-disable-next-line  // prettier-ignore
#       <!-- svelte-ignore a11y_… -->  <!-- @component … -->
#
#     Silencing a lint rule is precisely the edit that must expire coverage:
#     the scan seeds no-explicit-any and no-unused-vars, which is what a
#     developer reaches for a disable comment to hide. Without this the core
#     re-stamps coverage and the audit never revisits the file.
#
#     git takes one ERE and POSIX has no negative lookahead, so the property is
#     spelled positively: the first token of the comment body must contain
#     neither '@' nor '-'  ([^@[:space:]-]*), and anything after it is
#     unconstrained (so '// see https://x/a-b' stays trivial — only the leading
#     token is a directive slot). This deliberately errs toward NON-trivial: a
#     prose comment opening on a hyphenated word is treated as meaningful,
#     which is the safe direction per ADAPTERS.md — never re-stamp on doubt.
#
# The markup arm additionally requires the comment to open and close on the same
# line, so a multi-line <!-- --> block falls to the conservative default, as C#
# /* */ blocks already do. Its body is spelled ([^-]|-[^-]|--[^>])* — "anything
# up to the FIRST -->" — rather than the obvious '.*', which is greedy and would
# run to the LAST --> on the line, calling '<!-- a --> markup <!-- b -->' a
# comment-only line.
audit_trivial_comment_regex() {
    printf '%s' '^[[:space:]]*(//([[:space:]]+[^@[:space:]-]*([[:space:]].*)?)?$|<!--([[:space:]]+[^@[:space:]-]*([[:space:]]([^-]|-[^-]|--[^>])*)?)?-->[[:space:]]*$)'
}

